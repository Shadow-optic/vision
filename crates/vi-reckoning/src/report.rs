#[derive(Serialize)]
struct PackageView {
    title: String,
    actor: crate::entity::Actor,
    score: crate::score::AbuseScore,
    evidence: Vec<crate::package::EvidenceRow>,
    statutes: Vec<&'static crate::statutes::Statute>,
    immunity: &'static [crate::statutes::ImmunityNote],
    destinations: Vec<&'static str>,
    ledger: Vec<LedgerRef>,
    advocacy: crate::sentencing::SentenceAdvocacy,
    is_criminal: bool,
    is_civil: bool,
    is_bar: bool,
    is_sentencing: bool,
}

pub fn render_package(ctx: &PackageContext) -> Result<String, RenderError> {
    let title = match ctx.action_kind.as_str() {
        "criminal_referral" => "Criminal Referral Package",
        "civil_1983" => "Civil Rights Lawsuit Scaffold",
        "bar_complaint" => "Bar Disciplinary Complaint Draft",
        "sentencing_memo" => "Sentencing Advocacy Memorandum",
        other => other,
    };
    let view = PackageView {
        title: title.to_string(),
        actor: ctx.actor.clone(),
        score: ctx.score.clone(),
        evidence: ctx.evidence.clone(),
        statutes: ctx.statutes.clone(),
        immunity: ctx.immunity,
        destinations: ctx.destinations.clone(),
        ledger: ctx.ledger.clone(),
        advocacy: ctx.advocacy.clone(),
        is_criminal: ctx.action_kind == "criminal_referral",
        is_civil: ctx.action_kind == "civil_1983",
        is_bar: ctx.action_kind == "bar_complaint",
        is_sentencing: ctx.action_kind == "sentencing_memo",
    };
    let mut h = Handlebars::new();
    h.set_strict_mode(false);
    h.register_template_string("pkg", PACKAGE_TEMPLATE)?;
    Ok(h.render("pkg", &view)?)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::entity::Actor;
    use crate::package::{EvidenceRow, PackageContext};
    use crate::score::{AbuseScore, FORMULA};
    use crate::statutes;
    use serde_json::json;
    use uuid::Uuid;

    fn demo_ctx(kind: &str) -> PackageContext {
        PackageContext {
            actor: Actor {
                actor_id: Uuid::nil(),
                role: "prosecutor".into(),
                display_name: "Demo Prosecutor".into(),
                normalized_name: "demo prosecutor".into(),
                office: Some("Demo County DA".into()),
                jurisdiction: "CA".into(),
                bar_number: Some("CA-100001".into()),
                badge_number: None,
                prosecutor_id: None,
                fingerprint: "x".into(),
            },
            score: AbuseScore {
                actor_id: Uuid::nil(),
                score: 28.0,
                substantiated_findings: 1,
                substantiated_flags: 0,
                corroboration_sources: 1,
                recent_5yr: 1,
                formula: FORMULA,
                components: json!({}),
                snapshot_id: None,
            },
            action_kind: kind.into(),
            evidence: vec![EvidenceRow {
                source_kind: "constitutional_finding".into(),
                label: "brady".into(),
                citation: Some("Demo v. Demo (2024)".into()),
                summary: "Opinion notes missing chain of custody.".into(),
                case_id: None,
            }],
            statutes: statutes::for_finding_types(&["brady".into()]),
            immunity: statutes::IMMUNITY,
            destinations: vec!["State Attorney General (criminal division)"],
            ledger: vec![LedgerRef {
                seq: 1,
                event_type: "AbuseScoreComputed".into(),
                entry_hash: "abc".into(),
            }],
            advocacy: crate::sentencing::assemble(
                &statutes::for_finding_types(&["brady".into()]),
                false,
                false,
            ),
        }
    }

    #[test]
    fn criminal_referral_is_work_product_not_a_charge() {
        let md = render_package(&demo_ctx("criminal_referral")).unwrap();
        assert!(md.contains("Attorney Work Product"));
        assert!(md.contains("not a charging document"));
        assert!(md.contains("due-process"));
        assert!(md.contains("18 U.S.C."));
        assert!(md.contains("Demo Prosecutor"));
        assert!(!md.to_lowercase().contains("no mercy"));
        assert!(!md.to_lowercase().contains("life for life"));
    }

    #[test]
    fn sentencing_memo_advocates_statutory_maximum() {
        let md = render_package(&demo_ctx("sentencing_memo")).unwrap();
        assert!(md.contains("Sentencing Advocacy"));
        assert!(md.contains("same law"));
        assert!(md.contains("statutory maximum"));
        assert!(md.contains("Life imprisonment is not unlocked on this record"));
    }

    #[test]
    fn sentencing_memo_advocates_life_when_death_resulted() {
        let mut ctx = demo_ctx("sentencing_memo");
        ctx.advocacy = crate::sentencing::assemble(
            &statutes::for_finding_types(&["due_process".into()]),
            true,
            false,
        );
        let md = render_package(&ctx).unwrap();
        assert!(md.contains("life imprisonment"));
        assert!(md.contains("Counsel shall seek **life imprisonment**"));
    }
}
